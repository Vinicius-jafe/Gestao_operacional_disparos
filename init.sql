CREATE TABLE IF NOT EXISTS disparos_eventos (
    id VARCHAR(100) PRIMARY KEY,
    contrato VARCHAR(100),
    numero_contrato VARCHAR(100),
    chave_cliente VARCHAR(255),
    empresa VARCHAR(150),
    razao_social VARCHAR(255),
    departamento VARCHAR(100),
    hora_evento VARCHAR(50),
    dt_hora TIMESTAMP,
    data_evento DATE,
    ano_mes VARCHAR(7),
    hora_int INTEGER,
    minuto_do_dia INTEGER,
    final_de_semana BOOLEAN,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS carteira_filiais (
    filial VARCHAR(150) PRIMARY KEY,
    clientes INTEGER NOT NULL DEFAULT 0,
    tipo VARCHAR(50) NOT NULL DEFAULT 'FILIAL',
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS arquivos_processados (
    nome_arquivo VARCHAR(255) PRIMARY KEY,
    hash_sha256 VARCHAR(64) NOT NULL,
    tamanho_bytes BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL,
    linhas_lidas INTEGER DEFAULT 0,
    linhas_inseridas INTEGER DEFAULT 0,
    mensagem_erro TEXT,
    data_processamento TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS analise (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_providencia BIGINT,
    contrato VARCHAR(10),
    numero_contrato VARCHAR(20),
    empresa VARCHAR(150),
    razao_social VARCHAR(255),
    bairro VARCHAR(155),
    cidade VARCHAR(155),
    hora_evento VARCHAR(50),
    departamento VARCHAR(100),
    disparos INTEGER,
    dia DATE NOT NULL,
    hora VARCHAR(20),
    hora_cheia INTEGER,
    dia_semana VARCHAR(30),
    periodo VARCHAR(30),
    mes VARCHAR(30),
    estado VARCHAR(4),
    possivel_padrao VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS alarm_report_snapshots (
    id BIGSERIAL PRIMARY KEY,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    collected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    page_size INTEGER NOT NULL,
    page_count INTEGER NOT NULL,
    total_item_count INTEGER NOT NULL,
    CHECK (period_start <= period_end),
    CHECK (page_size > 0),
    CHECK (page_count >= 0),
    CHECK (total_item_count >= 0)
);

CREATE TABLE IF NOT EXISTS disparos_sensor (
    id BIGSERIAL PRIMARY KEY,
    snapshot_id BIGINT NOT NULL
        REFERENCES alarm_report_snapshots (id) ON DELETE CASCADE,
    cod_contrato TEXT,
    empresa TEXT,
    razao_social TEXT,
    num_contrato BIGINT NOT NULL,
    departamento TEXT,
    department_id INTEGER,
    department_mapping_confidence VARCHAR(20) NOT NULL
        CHECK (department_mapping_confidence IN ('OFICIAL', 'INFERIDO', 'CONTRACT_TYPE')),
    disparos INTEGER NOT NULL,
    message_count INTEGER NOT NULL,
    zona_disparos TEXT,
    data DATE NOT NULL,
    mes INTEGER NOT NULL CHECK (mes BETWEEN 1 AND 12),
    estado VARCHAR(4),
    modelo_sensor TEXT GENERATED ALWAYS AS (
        CASE
            WHEN zona_disparos IS NULL OR BTRIM(zona_disparos) = ''
                THEN 'VAZIO'
            WHEN UPPER(zona_disparos) LIKE '%BOTAO DE PANICO%'
              OR UPPER(zona_disparos) LIKE '%BOTÃO DE PÂNICO%'
              OR UPPER(zona_disparos) LIKE '%BPNA%'
              OR UPPER(zona_disparos) LIKE '%TRANSMISSOR%'
              OR UPPER(zona_disparos) LIKE '%TRANSMISSORES%'
              OR UPPER(zona_disparos) LIKE '%CONTROLES%'
              OR UPPER(zona_disparos) LIKE '%CONTROLE%'
                THEN 'BPNA'
            WHEN UPPER(zona_disparos) LIKE '%PRESENCA%'
              OR UPPER(zona_disparos) LIKE '%PRESENÇA%'
              OR UPPER(zona_disparos) LIKE '%RK%'
              OR UPPER(zona_disparos) LIKE '%RKS%'
              OR UPPER(zona_disparos) LIKE '%IVP%'
              OR UPPER(zona_disparos) LIKE '%IVPS%'
              OR UPPER(zona_disparos) LIKE '%BVS%'
              OR UPPER(zona_disparos) LIKE '%BV%'
              OR UPPER(zona_disparos) LIKE '%INFRA INTERNO%'
                THEN 'PRESENÇA'
            WHEN UPPER(zona_disparos) LIKE '%MAGNETICO%'
              OR UPPER(zona_disparos) LIKE '%MAGNÉTICO%'
              OR UPPER(zona_disparos) LIKE '%MAGNÉTICOS%'
              OR UPPER(zona_disparos) LIKE '%MAG%'
              OR UPPER(zona_disparos) LIKE '%FM%'
              OR UPPER(zona_disparos) LIKE '%TW%'
              OR UPPER(zona_disparos) LIKE '%JANELA%'
              OR UPPER(zona_disparos) LIKE '%JANELAS%'
              OR UPPER(zona_disparos) LIKE '%PORTAO%'
              OR UPPER(zona_disparos) LIKE '%PORTOES%'
              OR UPPER(zona_disparos) LIKE '%PORTÃO%'
              OR UPPER(zona_disparos) LIKE '%PORTÕES%'
                THEN 'MAGNÉTICO'
            WHEN UPPER(zona_disparos) LIKE '%IVA%'
              OR UPPER(zona_disparos) LIKE '%INFRAVERMELHO%'
              OR UPPER(zona_disparos) LIKE '%IVAS%'
              OR UPPER(zona_disparos) LIKE '%BARREIRA%'
              OR UPPER(zona_disparos) LIKE '%MURO%'
              OR UPPER(zona_disparos) LIKE '%INFRA EXTERNO%'
                THEN 'IVA'
            WHEN UPPER(zona_disparos) LIKE '%CERCA%' THEN 'CERCA'
            WHEN UPPER(zona_disparos) LIKE '%SEM ZONA%' THEN 'SEM ZONA'
            ELSE 'OUTRO / LOCAL'
        END
    ) STORED,
    UNIQUE (snapshot_id, num_contrato),
    CHECK (disparos >= 0),
    CHECK (message_count >= 0)
);

-- Índices essenciais para consultas rápidas
CREATE INDEX IF NOT EXISTS idx_disparos_empresa ON disparos_eventos (empresa);
CREATE INDEX IF NOT EXISTS idx_disparos_departamento ON disparos_eventos (departamento);
CREATE INDEX IF NOT EXISTS idx_disparos_ano_mes ON disparos_eventos (ano_mes);
CREATE INDEX IF NOT EXISTS idx_disparos_data_evento ON disparos_eventos (data_evento);
CREATE INDEX IF NOT EXISTS idx_disparos_chave_cliente ON disparos_eventos (chave_cliente);
CREATE INDEX IF NOT EXISTS idx_analise_dia_hora
    ON analise (dia, hora_cheia);
CREATE INDEX IF NOT EXISTS idx_alarm_report_snapshots_collected_at
    ON alarm_report_snapshots (collected_at);
CREATE INDEX IF NOT EXISTS idx_disparos_sensor_snapshot_department
    ON disparos_sensor (snapshot_id, department_id, data);

CREATE OR REPLACE VIEW vw_analise_disp_sensor AS
WITH snapshots_recentes AS (
    SELECT DISTINCT ON (period_start, period_end)
        id
    FROM alarm_report_snapshots
    ORDER BY period_start, period_end, collected_at DESC, id DESC
),
sensor_agrupado AS (
    SELECT
        TRIM(ds.cod_contrato) AS cod_contrato,
        ds.num_contrato,
        UPPER(TRIM(COALESCE(ds.departamento, ''))) AS departamento,
        UPPER(TRIM(COALESCE(ds.estado, ''))) AS estado,
        ds.data AS data_sensor,
        ds.modelo_sensor,
        MAX(ds.zona_disparos) AS zona_disparos,
        SUM(ds.disparos) AS qtd_modelo
    FROM disparos_sensor ds
    JOIN snapshots_recentes sr ON sr.id = ds.snapshot_id
    WHERE ds.modelo_sensor NOT IN ('VAZIO', 'SEM ZONA')
    GROUP BY
        TRIM(ds.cod_contrato),
        ds.num_contrato,
        UPPER(TRIM(COALESCE(ds.departamento, ''))),
        UPPER(TRIM(COALESCE(ds.estado, ''))),
        ds.data,
        ds.modelo_sensor
),
sensor_por_dia AS (
    SELECT
        cod_contrato,
        num_contrato,
        departamento,
        estado,
        data_sensor,
        STRING_AGG(
            modelo_sensor || ' (' || qtd_modelo || ')',
            ' | ' ORDER BY modelo_sensor
        ) AS sensores_no_dia,
        MAX(zona_disparos) AS zona_referencia_dia,
        SUM(qtd_modelo) AS total_disparos_sensor_dia
    FROM sensor_agrupado
    GROUP BY
        cod_contrato,
        num_contrato,
        departamento,
        estado,
        data_sensor
)
SELECT
    a.id,
    a.id_providencia,
    a.contrato,
    a.numero_contrato,
    a.empresa,
    a.razao_social,
    a.departamento,
    a.estado,
    a.dia,
    a.mes,
    a.hora_cheia,
    a.dia_semana,
    a.periodo,
    COALESCE(s.sensores_no_dia, 'SEM SENSOR NO DIA') AS sensores_no_dia,
    COALESCE(s.zona_referencia_dia, '-') AS zona_referencia_dia,
    COALESCE(s.total_disparos_sensor_dia, 0) AS total_disparos_sensor_dia
FROM analise a
LEFT JOIN sensor_por_dia s
    ON TRIM(COALESCE(a.contrato, '')) = s.cod_contrato
   AND CASE
       WHEN TRIM(COALESCE(a.numero_contrato, '')) ~ '^[0-9]+$'
       THEN TRIM(a.numero_contrato)::BIGINT
   END = s.num_contrato
   AND UPPER(TRIM(COALESCE(a.departamento, ''))) = s.departamento
   AND UPPER(TRIM(COALESCE(a.estado, ''))) = s.estado
   AND a.dia = s.data_sensor;

